/**
 * Neutral pre-generation rules, scope "All" (design-v2 4.4.10; REQ-IAC-008,
 * REQ-ADP-008). They run before any adapter rule. Adapter rules (AWS-*,
 * VSP-*) live with the adapter.
 *
 * Implemented here: L1 integrity errors (INT-*), IAC-E01, E02, E04, E06, E08,
 * TGT-E01 and IAC-E05 from the coverage query, IAC-W03, W07, W08, W09,
 * IAC-I01. IAC-E09 comes from context.ts, IAC-E12 from secrets.ts. E03 and
 * E07 depend on target data and are checked by adapters.
 */
import { getRole } from '../../graph/catalog'
import { canNest, effectiveFailureDomain } from '../../graph/containment'
import type { ArchGraphV2 } from '../../graph/types'
import { integrityErrors } from '../../graph/validate'
import { isValidCodeName } from '../../graph/codeName'
import type { IacAdapter } from './adapter'
import { resolveRealisation } from './coverage'
import { isSecretField, secretHits } from './secrets'
import type { IacProblem, TargetContext } from './types'

const nodePath = (doc: ArchGraphV2, nodeId: string) => `nodes[${doc.nodes.findIndex((node) => node.id === nodeId)}]`

export function neutralGate(ctx: TargetContext, adapter: IacAdapter): IacProblem[] {
  const { doc, coverage } = ctx
  const out: IacProblem[] = [...integrityErrors(doc)]
  out.push(...coverage.problems)

  const generatable = coverage.nodes.filter((row) => row.class === 'generatable')
  for (const row of generatable) {
    const node = ctx.byId.get(row.nodeId)!
    const path = nodePath(doc, node.id)
    if (!isValidCodeName(node.codeName)) {
      out.push({
        severity: 'error', ruleId: 'IAC-E04', path: `${path}.codeName`, nodeId: node.id,
        message: { en: `Code name ${JSON.stringify(node.codeName)} is not valid.`, vi: `Tên mã ${JSON.stringify(node.codeName)} không hợp lệ.` },
        fix: { en: 'Use lower-case letters, digits and _; start with a letter.', vi: 'Dùng chữ thường, số và _; bắt đầu bằng chữ cái.' },
      })
    }
    const parent = node.parentId !== undefined ? ctx.byId.get(node.parentId) : undefined
    const verdict = canNest(node.type, parent ? parent.type : null)
    if (!verdict.ok) {
      out.push({ severity: 'error', ruleId: 'IAC-E02', path: `${path}.parentId`, nodeId: node.id, message: verdict.message,
        fix: { en: 'Move the component into an allowed container.', vi: 'Chuyển thành phần vào vùng chứa hợp lệ.' } })
    }
    const realisation = resolveRealisation(node, doc, ctx.profile.target, adapter.catalogue).realisation
    for (const key of realisation?.requires ?? []) {
      const value = node.config?.[key]
      if (value === undefined || value === '' || (Array.isArray(value) && value.length === 0)) {
        out.push({
          severity: 'error', ruleId: 'IAC-E01', path: `${path}.config.${key}`, nodeId: node.id,
          message: { en: `${node.codeName} needs ${key} to generate on ${ctx.profile.target}.`, vi: `${node.codeName} cần ${key} để sinh mã cho ${ctx.profile.target}.` },
          fix: { en: `Set ${key} in the inspector.`, vi: `Đặt ${key} trong bảng thuộc tính.` },
        })
      }
    }
  }

  // IAC-E06: secret-looking literals in anything that reaches the package.
  const scan = (where: string, key: string, value: unknown, nodeId?: string) => {
    const values = Array.isArray(value) ? value : [value]
    const hit = isSecretField(key, value) || values.some((item) => typeof item === 'string' && secretHits(`${key} = "${item}"`).length > 0)
    if (hit) {
      out.push({
        severity: 'error', ruleId: 'IAC-E06', path: where, ...(nodeId ? { nodeId } : {}),
        message: { en: `${where} holds what looks like a secret.`, vi: `${where} có vẻ chứa bí mật.` },
        fix: { en: 'Remove it; secrets are supplied at run time, never stored in the design.', vi: 'Xóa đi; bí mật được cung cấp khi chạy, không lưu trong thiết kế.' },
      })
    }
  }
  for (const node of doc.nodes) {
    if (!ctx.onTarget.has(node.id)) continue
    for (const [key, value] of Object.entries(node.config ?? {})) scan(`${nodePath(doc, node.id)}.config.${key}`, key, value, node.id)
  }
  ;(doc.deployment?.bindings ?? []).forEach((binding, index) => {
    if (binding.target !== ctx.profile.target || !ctx.onTarget.has(binding.nodeId)) return
    for (const [key, value] of Object.entries(binding.config ?? {})) scan(`deployment.bindings[${index}].config.${key}`, key, value, binding.nodeId)
  })
  for (const [key, value] of Object.entries(ctx.profile.options ?? {})) scan(`deployment.profiles.${ctx.profile.id}.options.${key}`, key, value)

  if (generatable.length === 0) {
    out.push({
      severity: 'error', ruleId: 'IAC-E08', path: 'nodes',
      message: { en: `No component can be generated by ${adapter.id} on ${ctx.profile.id}.`, vi: `Không có thành phần nào ${adapter.id} sinh được trên ${ctx.profile.id}.` },
      fix: { en: 'The manual checklist (MANUAL-STEPS.md) can still be downloaded.', vi: 'Vẫn có thể tải danh sách việc thủ công (MANUAL-STEPS.md).' },
    })
  }

  for (const row of generatable) {
    const node = ctx.byId.get(row.nodeId)!
    const role = getRole(node.type)
    if (!role || role.container) continue
    const replicas = node.attributes?.replicas ?? role.defaultAttributes.replicas ?? 1
    const stateful = (node.attributes?.statefulness ?? role.defaultAttributes.statefulness) === 'stateful'
    const critical = (node.attributes?.criticality ?? role.defaultAttributes.criticality) === 'high'
    if ((stateful || critical) && replicas < 2) {
      out.push({ severity: 'warning', ruleId: 'IAC-W03', path: `${nodePath(doc, node.id)}.attributes.replicas`, nodeId: node.id,
        message: { en: `${node.codeName} is ${stateful ? 'stateful' : 'high-criticality'} with one replica.`, vi: `${node.codeName} ${stateful ? 'có trạng thái' : 'quan trọng cao'} nhưng chỉ có một bản sao.` } })
    }
    const level = node.attributes?.failureDomainLevel ?? effectiveFailureDomain(doc, node.id).level
    if (node.attributes?.failureDomainLevel && level && !adapter.supportedFailureDomainLevels.includes(level)) {
      out.push({ severity: 'warning', ruleId: 'IAC-W08', path: `${nodePath(doc, node.id)}.attributes.failureDomainLevel`, nodeId: node.id,
        message: {
          en: `${node.codeName}: failure-domain level ${level} cannot be expressed by ${adapter.id} (supports ${adapter.supportedFailureDomainLevels.join(', ')}).`,
          vi: `${node.codeName}: mức miền lỗi ${level} không biểu diễn được bằng ${adapter.id} (hỗ trợ ${adapter.supportedFailureDomainLevels.join(', ')}).`,
        } })
    }
  }

  const excluded = coverage.nodes.filter((row) => row.class === 'manual' || row.class === 'unsupported')
  if (excluded.length > 0) {
    const names = excluded.map((row) => row.codeName).join(', ')
    out.push({ severity: 'warning', ruleId: 'IAC-W07', path: 'nodes',
      message: { en: `Not generated (listed in COVERAGE.md and MANUAL-STEPS.md): ${names}.`, vi: `Không sinh mã (có trong COVERAGE.md và MANUAL-STEPS.md): ${names}.` } })
  }
  const other = coverage.nodes.filter((row) => row.class === 'assignedToOtherTarget')
  if (other.length > 0) {
    out.push({ severity: 'warning', ruleId: 'IAC-W09', path: 'deployment.scenarios',
      message: { en: `${other.length} component(s) are placed on another target and excluded from this package.`, vi: `${other.length} thành phần thuộc đích khác và không có trong gói này.` } })
  }
  const annotations = coverage.nodes.filter((row) => row.class === 'annotation')
  if (annotations.length > 0) {
    out.push({ severity: 'info', ruleId: 'IAC-I01', path: 'nodes',
      message: { en: `${annotations.length} annotation or external component(s) produce no code.`, vi: `${annotations.length} chú thích hoặc thành phần bên ngoài không sinh mã.` } })
  }
  return out
}

const SEVERITY_RANK = { error: 0, warning: 1, info: 2 } as const

/** Errors, then warnings, then info; within a severity the order found (stable sort). */
export function sortProblems(problems: IacProblem[]): IacProblem[] {
  return problems.map((problem, index) => ({ problem, index }))
    .sort((a, b) => SEVERITY_RANK[a.problem.severity] - SEVERITY_RANK[b.problem.severity] || a.index - b.index)
    .map(({ problem }) => problem)
}
