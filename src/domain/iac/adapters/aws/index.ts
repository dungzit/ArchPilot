/** Commands the CI harness runs in every golden folder (NFR2-COR-001). */
export const TERRAFORM_VALIDATION_COMMANDS: string[][] = [
  ['terraform', 'fmt', '-check', '-recursive', '-diff'],
  ['terraform', 'init', '-backend=false', '-input=false', '-no-color'],
  ['terraform', 'validate', '-json', '-no-color'],
]

export function fileHeader(adapterId: string, adapterVersion: string): string[] {
  return [
    `Generated by ArchPilot generator ${GENERATOR_VERSION}, adapter ${adapterId} ${adapterVersion}.`,
    'Do not edit by hand: change the design in ArchPilot and generate again.',
  ]
}

function terraformIr(ir: ToolIr): TerraformIr {
  if (!isTerraformIr(ir)) throw new Error(`expected a terraform IR, got ${ir.tool}`)
  return ir
}

export const awsTerraformAdapter: IacAdapter = {
  id: AWS_ADAPTER_ID,
  version: AWS_ADAPTER_VERSION,
  tool: 'terraform',
  targetKinds: ['aws'],
  toolConstraint: TERRAFORM_REQUIRED_VERSION,
  providerPins: [{ source: AWS_PROVIDER.source, constraint: AWS_PROVIDER.constraint }],
  supportedFailureDomainLevels: ['zone', 'region'],
  variableSchema: AWS_VARIABLE_SCHEMA,
  emittedFiles: [...TERRAFORM_FILES, 'COVERAGE.md', 'MANUAL-STEPS.md', 'README.md', 'archpilot-manifest.json'].sort(),
  pipelineTemplates: [],
  validationCommands: TERRAFORM_VALIDATION_COMMANDS,
  goldenFixtures: ['aws-three-tier', 'aws-network-nat-none', 'aws-network-nat-per-zone', 'aws-internal-platform', 'aws-injection'],
  catalogue: AWS_CATALOGUE,
  gate: awsGate,
  plan: awsPlan,
  manualSteps: awsManualSteps,
  files: (ir) => terraformFiles(terraformIr(ir), fileHeader(AWS_ADAPTER_ID, AWS_ADAPTER_VERSION)),
  readme: (ir, ctx) => awsReadme(terraformIr(ir), ctx),
}

function awsManualSteps(ctx: TargetContext): ManualStep[] {
  const { options } = awsOptions(ctx)
  const items = [
    `Create the Terraform state bucket (versioning and encryption on, public access blocked) in ${mdCode(options.region)}, then copy ${mdCode('backend.hcl.example')} to ${mdCode('backend.hcl')} and fill it in.`,
  ]
  for (const row of ctx.coverage.nodes) {
    if (row.class !== 'generatable') continue
    const node = ctx.byId.get(row.nodeId)!
    if (row.realisation === 'aws.alb' && String(configOf(node, 'protocol')) === 'https') {
      items.push(`Request or import an ACM certificate in ${mdCode(options.region)} for ${mdCode(node.codeName)} and set ${mdCode(`${node.codeName}_certificate_arn`)} in ${mdCode('terraform.tfvars')}.`)
    }
    if (row.realisation === 'aws.ecs_fargate') {
      items.push(`Build and push the image of ${mdCode(node.codeName)}, then set ${mdCode(`${node.codeName}_image`)} in ${mdCode('terraform.tfvars')}.`)
    }
  }
  const external = new Set(generatableLinks(ctx).filter((link) => link.target.type === 'external_service').map((link) => link.target.codeName))
  for (const codeName of [...external].sort()) items.push(`Set ${mdCode(`${codeName}_base_url`)} in ${mdCode('terraform.tfvars')}.`)
  return [{ codeName: 'before_first_plan', role: 'setup', items }]
}

function awsReadme(ir: TerraformIr, ctx: TargetContext): string[] {
  const required = ir.variables.filter((v) => v.default === undefined).map((v) => `- ${mdCode(v.name)}: ${v.description}`)
  const vpcs = ctx.coverage.nodes.filter((row) => row.realisation === 'aws.vpc' && row.class === 'generatable').length
  return [
    '## How to run',
    '',
    '```sh',
    'cp backend.hcl.example backend.hcl   # fill in the state bucket',
    'terraform init -backend-config=backend.hcl',
    'terraform validate',
    'terraform plan -out=tfplan',
    '```',
    '',
    'ArchPilot never runs `apply` or `destroy`. Review the plan, then apply it through your own approval process.',
    '',
    '## Required values',
    '',
    'These variables have no default; `terraform.tfvars` holds `CHANGE_ME` placeholders that fail at `plan` until replaced:',
    '',
    ...(required.length > 0 ? required : ['- None.']),
    '',
    '## Versions',
    '',
    `- Terraform ${mdCode(ir.requiredVersion)}`,
    ...ir.pins.map((pin) => `- ${mdCode(pin.source)} ${mdCode(pin.constraint)}; ${mdCode('.terraform.lock.hcl')} pins ${pin.locked} for linux_amd64, darwin_arm64 and windows_amd64.`),
    '',
    '## Security notes',
    '',
    '- Security groups allow only the ports that access edges need; `0.0.0.0/0` appears only on an internet-facing listener.',
    '- Exception (C-v2-2): services may open TCP 443 to the internet, through NAT, to pull images and call AWS APIs. Replace it with VPC endpoints if your policy requires.',
    '- Database master passwords are managed by RDS in Secrets Manager; no secret is written to any file.',
    ...(vpcs > 0 ? ['- The VPC default security group is emptied, so nothing can use it by accident.'] : []),
  ]
}
